const textEn = `# A world of one's own

*What if we took the time to gather what makes us feel alive?*

There are things we go through, ideas that brush past us, desires we keep somewhere in a corner of our mind. Projects that take shape, others that remain a dream. Small victories we forget almost as soon as they happen, moments whose delicacy we would still like to keep.

What if all of this deserved a place?

I believe we have sometimes unlearned how to create simply for the pleasure of creating. To play, to experiment, to try without necessarily trying to succeed. We have grown used to measuring what we do, comparing it, looking for its usefulness, its profitability, its legitimacy. As if we always had to justify the time we give to what moves us.

And yet, not everything needs to become a profession, a performance or an exceptional achievement to have value.

We all have things to tell, to imagine, to build. A passion, a reflection, a skill, a slightly crazy idea, a collection of memories, a few photographs, words, experiences. We all have fragments that belong to us and that, put together, draw something unique.

**I like to imagine that each of us brings our own piece to an infinitely vaster puzzle, whose edges we do not know, nor truly its picture.** Some pieces seem orderly, others completely out of place. Some fit together straight away, others are still waiting to meet. But all of them have their place, even in the apparent disorder of the whole.

What if we simply took the time to discover what we have to bring to it?

### Another way to remember

There is an idea that stays with me: if one day I had to surround myself with my memories, I would like them to look like this world.

We sometimes find it strangely easy to remember our mistakes, our failures, our regrets. Sadness, disappointments and the reproaches we address to ourselves can take up a considerable amount of space. They sometimes end up becoming the walls of a mental prison we lock ourselves into without even noticing.

But it is so much harder to remember our own victories.

Not necessarily the great successes we tell others about. Rather those small things that did us good: a project we dared to start, a difficulty we finally overcame, an encounter, a discovery, an idea we managed to bring to life. Those moments when we felt alive, proud, inspired, free. Those emotions, sometimes quiet, whose intensity remains precious.

I do not wish to deny the darker passages of our stories. They are part of us. But I refuse to give them all of our memory.

So, if I had to keep a few memories around me, I would like them to be these. The ones that remind me of what I loved, what I tried, what I learned, what I dared to become.

**To make this space a kind of living refuge: not a prison of memories, but a world in which it would be gentle to find oneself again.**

### Creating, for oneself. And perhaps with others.

This is also what made me want to design this space as a portfolio, though not necessarily in the professional sense of the word.

A portfolio can be much more than a showcase of skills. It can become a logbook, a laboratory of ideas, a personal gallery, a project journal, a space for expression or even a small world of its own.

There is no required form. It can be sober, contemplative, artistic, experimental, unconventional, playful or resolutely professional. It can evolve with us, welcome our changes, our new desires and all those things we might never have thought of gathering in one place.

What matters is not knowing how to code, mastering a discipline or having an extraordinary background. It is wanting to give shape to something that resembles us.

And if an idea seems too complex, too original or completely impossible, that is precisely what interests me. I love learning, exploring new possibilities, taking on technical challenges and discovering how far an idea can take us.

I can therefore accompany you in creating your own space, starting from your desires, your personality and your imagination. We can think together about its form, its atmosphere, its content and everything that could make it singular.

I want to make this approach accessible, without it becoming an intimidating service or an obligation to deliver. We can simply talk about an idea, with no commitment, imagine what would be possible and see how far we want to take it.

And who knows what can grow from this first step? A portfolio can become the starting point of an artistic project, a professional activity, a collective initiative, a collaboration or something that does not have a name yet. A space first imagined for oneself can end up opening doors we never suspected.

It is not necessarily about knowing from the start where we want to go. Sometimes, giving an idea a first shape is enough to bring new possibilities to light.

The projects may be very different, and that is precisely what I love: each world tells something the previous one could not tell.

### What if we shared our worlds too?

I love learning from others, discovering their sensibilities, their ways of thinking and the worlds they carry within them.

I believe there is something particularly stimulating in bringing imaginations together, crossing skills and letting two ideas give birth to a third.

That is why this space is not meant to stay closed in on itself. It could also become a meeting point, an invitation to collaborate, to share creations, to bring projects to light and to give birth to new desires.

Perhaps an idea that seemed insignificant to one person will become a true source of inspiration for another.

After all, we never really know what our small pieces can spark when they meet those of others.

### One last thought

I recently discovered the Japanese notion of *ikigai*, often translated as "a reason for living" or "a reason to get up in the morning". In all its richness, it evokes what gives our existence a particular flavour: the things that move us, the bonds we weave, the activities that nourish us and the feeling of contributing, in our own way, to something.

I found it interesting to find in it an echo of some of these reflections, as if ideas we believed to be isolated could sometimes meet.

Perhaps it simply starts there: learning to recognise what does us good, what makes us want to try, what awakens our curiosity.

I do not claim to have found a universal answer. I am still searching, too. And perhaps that is precisely the point.

So, if this space makes you want to create your own, to gather your fragments, to give shape to your ideas or simply to allow yourself to try something new, I would be delighted.

**We all have a world to discover, and perhaps a few pieces of other people's to meet.**

*We might as well give them a place to exist.*`

