const textFr = `# Un univers à soi

*Et si nous prenions le temps de rassembler ce qui nous fait vivre ?*

Il y a des choses que l'on traverse, des idées qui nous effleurent, des envies que l'on garde quelque part dans un coin de la tête. Des projets qui prennent forme, d'autres qui restent à l'état de rêve. Des petites victoires que l'on oublie presque aussitôt, des instants dont on aimerait pourtant conserver la délicatesse.

Et si tout cela méritait un endroit ?

Je crois que nous avons parfois désappris à créer simplement pour le plaisir de créer. À jouer, à expérimenter, à essayer sans nécessairement chercher à réussir. Nous avons pris l'habitude de mesurer ce que nous faisons, de le comparer, de lui chercher une utilité, une rentabilité, une légitimité. Comme s'il fallait toujours justifier le temps que l'on consacre à ce qui nous anime.

Pourtant, tout n'a pas besoin de devenir un métier, une performance ou une réalisation exceptionnelle pour avoir de la valeur.

Nous avons tous des choses à raconter, à imaginer, à construire. Une passion, une réflexion, un savoir-faire, une idée un peu folle, une collection de souvenirs, quelques photographies, des mots, des expériences. Nous avons tous des fragments qui nous appartiennent et qui, mis bout à bout, dessinent quelque chose d'unique.

**J'aime imaginer que chacun de nous apporte sa propre pièce à un puzzle infiniment plus vaste, dont nous ne connaissons ni les contours ni véritablement le dessin.** Certaines pièces semblent ordonnées, d'autres complètement décalées. Certaines s'assemblent immédiatement, d'autres attendent leur rencontre. Mais toutes ont leur place, jusque dans le désordre apparent de l'ensemble.

Et si nous prenions simplement le temps de découvrir ce que nous avons à y apporter ?

### Une autre manière de se souvenir

Il y a une idée qui m'accompagne : si je devais un jour m'entourer de mes souvenirs, j'aimerais qu'ils ressemblent à cet univers.

Nous avons parfois une étrange facilité à nous rappeler nos erreurs, nos échecs, nos regrets. La tristesse, les déceptions et les reproches que l'on s'adresse à soi-même peuvent prendre une place considérable. Ils finissent parfois par devenir les murs d'une prison mentale dans laquelle on s'enferme sans même s'en apercevoir.

Mais il est tellement plus difficile de se souvenir de ses propres victoires.

Pas nécessairement des grandes réussites que l'on raconte aux autres. Plutôt de ces petites choses qui nous ont fait du bien : un projet que l'on a osé commencer, une difficulté que l'on a fini par dépasser, une rencontre, une découverte, une idée que l'on a réussi à concrétiser. Ces moments où l'on s'est senti vivant, fier, inspiré, libre. Ces émotions parfois discrètes, mais dont l'intensité reste précieuse.

Je ne souhaite pas nier les passages plus sombres de nos histoires. Ils font partie de nous. Mais je refuse de leur réserver toute la mémoire.

Alors, si je devais conserver quelques souvenirs autour de moi, j'aimerais qu'ils soient ceux-ci. Ceux qui me rappellent ce que j'ai aimé, ce que j'ai tenté, ce que j'ai appris, ce que j'ai osé devenir.

**Faire de cet espace une sorte de refuge vivant : non pas une prison de souvenirs, mais un univers dans lequel il serait doux de se retrouver.**

### Créer, pour soi. Et peut-être avec les autres.

C'est aussi ce qui m'a donné envie de concevoir cet espace comme un portfolio, mais pas nécessairement au sens professionnel du terme.

Un portfolio peut être bien davantage qu'une vitrine de compétences. Il peut devenir un carnet de bord, un laboratoire d'idées, une galerie personnelle, un journal de projets, un espace d'expression ou même un petit monde à part entière.

Il n'existe aucune forme imposée. Il peut être sobre, contemplatif, artistique, expérimental, atypique, ludique ou résolument professionnel. Il peut évoluer avec nous, accueillir nos changements, nos nouvelles envies et toutes ces choses que nous n'aurions peut-être jamais pensé réunir au même endroit.

L'essentiel n'est pas de savoir coder, de maîtriser une discipline ou de posséder un parcours extraordinaire. C'est d'avoir envie de donner forme à quelque chose qui nous ressemble.

Et si une idée paraît trop complexe, trop originale ou complètement irréalisable, c'est justement ce qui m'intéresse. J'aime apprendre, explorer de nouvelles possibilités, relever des défis techniques et découvrir jusqu'où une idée peut nous emmener.

Je peux ainsi vous accompagner dans la création de votre propre espace, en partant de vos envies, de votre personnalité et de votre imagination. Nous pouvons réfléchir ensemble à sa forme, à son ambiance, à son contenu et à tout ce qui pourrait le rendre singulier.

Je souhaite rendre cette démarche accessible, sans qu'elle devienne une prestation intimidante ou une obligation de résultat. Nous pouvons simplement échanger autour d'une idée, sans engagement, imaginer ce qui serait possible et voir jusqu'où nous avons envie de la faire évoluer.

Et qui sait ce qui peut naître de ce premier pas ? Un portfolio peut devenir le point de départ d'un projet artistique, d'une activité professionnelle, d'une initiative collective, d'une collaboration ou de quelque chose qui n'a pas encore de nom. Un espace imaginé au départ pour soi peut finalement ouvrir des portes que l'on ne soupçonnait pas.

Il ne s'agit pas nécessairement de savoir dès le départ où l'on veut aller. Parfois, donner une première forme à une idée suffit à faire apparaître de nouvelles possibilités.

Les projets pourront être très différents, et c'est précisément ce qui me plaît : chaque univers raconte quelque chose que le précédent ne pouvait pas raconter.

### Et si l'on partageait aussi nos univers ?

J'aime apprendre des autres, découvrir leurs sensibilités, leurs façons de penser et les mondes qu'ils portent en eux.

Je crois qu'il y a quelque chose de particulièrement stimulant dans le fait de confronter des imaginaires, de croiser des compétences et de laisser deux idées en faire naître une troisième.

C'est pourquoi cet espace n'a pas vocation à rester fermé sur lui-même. Il pourrait aussi devenir un point de rencontre, une invitation à collaborer, à partager des créations, à faire découvrir des projets et à donner naissance à de nouvelles envies.

Peut-être qu'une idée qui semblait insignifiante pour l'un deviendra une véritable source d'inspiration pour l'autre.

Après tout, nous ne savons jamais vraiment ce que nos petites pièces peuvent provoquer lorsqu'elles rencontrent celles des autres.

### Une dernière pensée

J'ai découvert récemment cette notion japonaise d'*ikigai*, souvent traduite par « raison de vivre » ou « raison de se lever le matin ». Elle évoque, dans toute sa richesse, ce qui donne à notre existence une saveur particulière : les choses qui nous animent, les liens que nous tissons, les activités qui nous nourrissent et le sentiment de contribuer, à notre manière, à quelque chose.

J'ai trouvé intéressant d'y retrouver un écho à certaines de ces réflexions, comme si des idées que l'on croyait isolées pouvaient parfois se rejoindre.

Peut-être que cela commence simplement par là : apprendre à reconnaître ce qui nous fait du bien, ce qui nous donne envie d'essayer, ce qui éveille notre curiosité.

Je ne prétends pas avoir trouvé de réponse universelle. Je cherche encore, moi aussi. Et c'est peut-être justement le principe.

Alors, si cet espace vous donne envie de créer le vôtre, de rassembler vos fragments, de donner une forme à vos idées ou simplement de vous autoriser à essayer quelque chose de nouveau, j'en serais ravie.

**Nous avons tous un univers à découvrir, et peut-être quelques morceaux de celui des autres à rencontrer.**

*Autant leur laisser un endroit où exister.*`

